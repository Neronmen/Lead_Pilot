// Regenerates src/tlds.ts from the `tlds` package (the IANA root zone list).
//   pnpm --filter @leadpilot/shared tlds
// Offline: the package ships the list. Run it after upgrading `tlds`; a test
// fails when src/tlds.ts and the installed package disagree.
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const tlds = createRequire(import.meta.url)('tlds');
// Plain-letter endings only: addresses are ASCII, and the email syntax check
// already refuses internationalised (xn--) endings.
const plain = tlds.filter((tld) => /^[a-z]+$/.test(tld)).sort();
// One entry per line: the format Prettier keeps, so `format:check` stays green.
const lines = plain.map((tld) => `  '${tld}',`);
const source = `// Generated by scripts/generate-tlds.mjs from the \`tlds\` package. Do not edit.
// The IANA root zone's plain-letter top-level domains (${plain.length}).
export const TLDS: readonly string[] = [
${lines.join('\n')}
];
`;
writeFileSync(fileURLToPath(new URL('../src/tlds.ts', import.meta.url)), source);
console.log(`wrote src/tlds.ts with ${plain.length} endings`);
